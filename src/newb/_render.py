"""Render a ``newb.run`` report dict as a README-ready markdown block.

Extracted from ``_try.py`` for line-budget hygiene. Pure formatter:
no I/O, no SDK calls, no host-side state. Re-exported from
``newb.__init__`` so ``newb.render_markdown(report)`` keeps working.
"""

from __future__ import annotations

import datetime
from typing import Any, Dict


def render_markdown(payload: Dict[str, Any]) -> str:
    """Render ``run`` output as a README-ready markdown block."""
    pkg = payload.get("package", "<package>")
    today = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d")
    parts: list[str] = [
        "## Skills Quality (verified by agent)",
        "",
        "> Generated by a fresh agent reading only this package's `_skills/` directory.",
        f"> Package: `{pkg}`. Last verified: {today} (UTC).",
        "",
    ]
    info = payload.get("runtime_info")
    if isinstance(info, dict) and info:
        parts += ["```yaml", "# runtime_info"]
        for key in (
            "newb_version",
            "runtime",
            "image",
            "model",
            "template",
            "scope",
            "skills_path",
            "agent_resources",
        ):
            if key in info:
                parts.append(f"{key}: {info[key]}")
        if "setting_sources" in info:
            parts.append(f"setting_sources: {info['setting_sources']}")
        hardening = info.get("hardening")
        if isinstance(hardening, dict) and hardening:
            parts.append("hardening:")
            for k, v in hardening.items():
                parts.append(f"  {k}: {v}")
        parts += ["```", ""]

    def _block(value: Any) -> str:
        if isinstance(value, list):
            return "\n\n---\n\n".join(str(v) for v in value)
        return str(value)

    if "what_for" in payload:
        parts += [
            "**Q: What is this package for?**",
            "",
            "> " + _block(payload["what_for"]).replace("\n", "\n> "),
            "",
        ]
    if "problems_solved" in payload:
        parts += [
            "**Q: What problems does it solve?**",
            "",
            _block(payload["problems_solved"]).strip(),
            "",
        ]
    if "quick_start" in payload:
        parts += [
            "**Q: How do I use it?**",
            "",
            _block(payload["quick_start"]).strip(),
            "",
        ]
    if "when_not_to_use" in payload:
        parts += [
            "**Q: When should I NOT use this?**",
            "",
            "> " + _block(payload["when_not_to_use"]).replace("\n", "\n> "),
            "",
        ]
    if "post_install_check" in payload:
        parts += [
            "**Q: Does it install + import + smoke-run cleanly?**",
            "",
            _block(payload["post_install_check"]).strip(),
            "",
        ]
    if "subcommand_tree" in payload:
        parts += [
            "**Q: What subcommands / CLI surface does it expose?**",
            "",
            _block(payload["subcommand_tree"]).strip(),
            "",
        ]
    if "typical_usage" in payload:
        parts += [
            "**Q: What does typical usage look like?**",
            "",
            _block(payload["typical_usage"]).strip(),
            "",
        ]
    if "common_pitfall" in payload:
        parts += [
            "**Q: What's a common pitfall?**",
            "",
            "> " + _block(payload["common_pitfall"]).replace("\n", "\n> "),
            "",
        ]
    if "install_and_help" in payload:
        parts += [
            "**Q: How do I install it and get help?**",
            "",
            _block(payload["install_and_help"]).strip(),
            "",
        ]
    if "prompt_injection_check" in payload:
        parts += [
            "**Q: Prompt-injection sweep across the docs?**",
            "",
            _block(payload["prompt_injection_check"]).strip(),
            "",
        ]
    boundary = payload.get("tests") or []
    if boundary:
        parts += ["### Boundary tests", ""]
        for entry in boundary:
            mark = "PASS" if entry.get("passed") else "FAIL"
            parts += [
                f"- **Q:** {entry['prompt']}",
                f"  - **A:** {entry['answer'].strip()} [{mark}]",
            ]
        parts.append("")

    sig = payload.get("newb_signature")
    if isinstance(sig, dict) and sig:
        version = sig.get("version", "?")
        pypi = sig.get("pypi", "")
        github = sig.get("github", "")
        eco = sig.get("ecosystem") or {}
        eco_name = eco.get("name") if isinstance(eco, dict) else None
        eco_url = eco.get("url") if isinstance(eco, dict) else None
        tagline = sig.get("tagline", "")
        parts += [
            "---",
            "",
            f"*{tagline}*" if tagline else "",
            f"Verified by **[newb]({github})** v{version} "
            f"([PyPI]({pypi}))"
            + (
                f" · part of **[{eco_name}]({eco_url})**"
                if eco_name and eco_url
                else ""
            )
            + ".",
            "",
        ]

    return "\n".join(parts).rstrip() + "\n"


